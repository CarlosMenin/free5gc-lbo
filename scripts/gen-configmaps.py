#!/usr/bin/env python3
"""
Regenerates manifests/apps/code-configmaps.yaml from the Python sources.

The Application Function (af/mec_af.py) and the traffic probe (probe/probe.py)
are not packaged as container images: each source file is mounted into a stock
python:3.12-slim container from a ConfigMap. This script embeds the current
sources into those ConfigMaps.

Run it after editing either source file, then apply and restart the pods that
mount the code (a ConfigMap change does not restart them):

    python3 scripts/gen-configmaps.py
    kubectl apply -f manifests/apps/code-configmaps.yaml
    kubectl -n free5gc rollout restart deploy/mec-af
"""
import argparse
import hashlib
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = "manifests/apps/code-configmaps.yaml"

# (ConfigMap name, source file relative to the repository root)
SOURCES = [
    ("mec-af", "af/mec_af.py"),
    ("lbo-probe", "probe/probe.py"),
]

HEADER = """# GENERATED by scripts/gen-configmaps.py -- do not edit by hand.
# Sources: {sources}
"""

CONFIGMAP = """apiVersion: v1
kind: ConfigMap
metadata:
  name: {name}
  namespace: {ns}
  annotations:
    source-sha256: "{digest}"
data:
  {key}: |
{code}
"""


def digest_of(path):
    with open(path, "rb") as fh:
        return hashlib.sha256(fh.read()).hexdigest()


def build(namespace):
    parts = []
    for name, rel in SOURCES:
        path = os.path.join(ROOT, rel)
        body = open(path).read()
        code = "\n".join(("    " + line) if line.strip() else ""
                         for line in body.rstrip("\n").split("\n"))
        parts.append(CONFIGMAP.format(name=name, ns=namespace, digest=digest_of(path),
                                      key=os.path.basename(rel), code=code))
    header = HEADER.format(sources=", ".join(rel for _, rel in SOURCES))
    return header + "---\n".join(parts)


def main():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--namespace", default="free5gc")
    parser.add_argument("--out", default=OUT, help=f"output file (default: {OUT})")
    args = parser.parse_args()

    path = args.out if os.path.isabs(args.out) else os.path.join(ROOT, args.out)
    with open(path, "w") as fh:
        fh.write(build(args.namespace))
    print(f"written {os.path.relpath(path, ROOT)} (namespace {args.namespace})")


if __name__ == "__main__":
    main()
